//! BLUT Kubernetes operator (ADR 0067 T4.5).
//!
//! Kubernetes is an adapter, not the control plane: the operator runs each
//! `BlutPlan` as a Job and keeps each `BlutWorkerPool` StatefulSet alive, and
//! the engine inside the pod still owns execution, caching and admission. All
//! kube-rs code lives in this crate; the engine (`blut`) has no Kubernetes
//! dependency and submits plans by rendering a manifest for `kubectl`
//! (`LaunchTarget::K8s`).
//!
//! Install, CRD reference and limits: `docs/OPERATOR.md` in the BLUT
//! repository.

pub mod crds;
pub mod reconcile;

pub use crds::{
    BlutPlan, BlutPlanSpec, BlutPlanStatus, BlutWorkerPool, BlutWorkerPoolSpec,
    BlutWorkerPoolStatus, CacheConfig, DataClassCeiling, PlanPhase, PlanResources, PlanSource,
    PoolResources, StoreConfig,
};

/// Both CRDs as one multi-document YAML stream, exactly what
/// `blut-operator crds` prints and `deploy/crds.yaml` in this crate holds.
pub fn crds_yaml() -> Result<String, serde_yaml::Error> {
    use kube::CustomResourceExt;
    let plan = serde_yaml::to_string(&BlutPlan::crd())?;
    let pool = serde_yaml::to_string(&BlutWorkerPool::crd())?;
    Ok(format!(
        "# Generated by `blut-operator crds`. Do not edit; regenerate.\n---\n{plan}---\n{pool}"
    ))
}
